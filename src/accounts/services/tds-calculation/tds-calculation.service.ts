import { Injectable } from '@nestjs/common';
import { Prisma } from '@prisma/client';
import { DatabaseService } from 'src/database/database.service';
import { toNumber } from 'src/common/helper';

type Tx = Prisma.TransactionClient | DatabaseService;

export interface GetSupplierTdsContextDto {
  CustomerBranchSid: number;
  LedgerMasterSid: number;
  CompanyMasterSid: number;
  fyStartDate: Date;
  fyEndDate: Date;
  voucherDate: Date;
  excludeVoucherHeaderSid?: number;
}

export interface CreateVoucherTDSDto {
  CompanyMasterSid: number;
  BranchMasterSid: number;
  VoucherHeaderSid: number;
  VoucherDetailSid?: number | null;
  TDSSetRateSid: number;
  ITSectionCode: string;
  TDSRate: number;
  TaxableAmount: number;
  TDSAmount: number;
  TDSPartyAmount?: number | null;
  Reason?: string | null;
  CreatedBy?: string;
  UpdatedBy?: string;
  Status?: string;
}

@Injectable()
export class TdsCalculationService {
  constructor(private _db: DatabaseService) {}

  /**
   * Returns the SupplierTdsMapping (if active for the given voucher date), the
   * Customer's CompanyType (used for filtering applicable TDSSetRate rows),
   * and the FY cumulative TaxableAmount of payments made to this vendor.
   *
   * Cumulative is sourced from VoucherTransaction (not VoucherTDS) so that
   * payments without TDS deduction still count toward the annual threshold.
   */
  async getSupplierTdsContext(dto: GetSupplierTdsContextDto) {
    const voucherDate = dto.voucherDate ?? new Date();

    const [mapping, customerBranch, agg] = await Promise.all([
      this._db.supplierTdsMapping.findFirst({
        where: {
          CustomerBranchSid: dto.CustomerBranchSid,
          CompanyMasterSid: dto.CompanyMasterSid,
          Status: 'A',
          EffectiveFrom: { lte: voucherDate },
          EffectiveTo: { gte: voucherDate },
        },
        include: {
          tdsSetHeader: {
            include: {
              tdsSetRate: { where: { status: 'A' } },
            },
          },
        },
      }),
      this._db.customerBranch.findUnique({
        where: { CustomerBranchSid: dto.CustomerBranchSid },
        select: {
          CustomerMasterSid: true,
          customerMaster: { select: { CompanyType: true } },
        },
      }),
      this._db.voucherTransaction.aggregate({
        where: {
          CompanyMasterSid: dto.CompanyMasterSid,
          LedgerMasterSid: dto.LedgerMasterSid,
          DrCr: 'D',                  // Dr-to-vendor (payment outflow / liability settled)
          Status: 'A',
          IsAutoGenerated: { not: 'Y' },
          VoucherHeader: {
            PostStatus: 'P',
            VoucherDate: { gte: dto.fyStartDate, lte: dto.fyEndDate },
            ...(dto.excludeVoucherHeaderSid
              ? { VoucherHeaderSid: { not: dto.excludeVoucherHeaderSid } }
              : {}),
          },
        },
        _sum: { LocalAmount: true },   // LocalAmount = pre-tax base in this app
      }),
    ]);

    const customerCompanyType =
      mapping?.CompanyType ?? customerBranch?.customerMaster?.CompanyType ?? null;

    return {
      mapping,
      customerCompanyType,
      cumulativeTaxableAmount: toNumber(agg._sum.LocalAmount ?? 0),
    };
  }

  resolveApplicableRate(rates: any[], voucherDate: Date): any | null {
    return (
      rates
        .filter(r => new Date(r.EffectiveFrom) <= voucherDate)
        .sort(
          (a, b) =>
            new Date(b.EffectiveFrom).getTime() - new Date(a.EffectiveFrom).getTime(),
        )[0] ?? null
    );
  }

  async createVoucherTDS(data: CreateVoucherTDSDto, tx: Tx) {
    return tx.voucherTDS.create({
      data: {
        CompanyMasterSid: data.CompanyMasterSid,
        BranchMasterSid: data.BranchMasterSid,
        VoucherHeaderSid: data.VoucherHeaderSid,
        VoucherDetailSid: data.VoucherDetailSid ?? null,
        TDSSetRateSid: data.TDSSetRateSid,
        ITSectionCode: data.ITSectionCode,
        TDSRate: Math.round(Number(data.TDSRate) || 0),
        TaxableAmount: data.TaxableAmount,
        TDSAmount: data.TDSAmount,
        TDSPartyAmount: data.TDSPartyAmount ?? null,
        Reason: data.Reason ?? null,
        CreatedBy: data.CreatedBy ?? 'system',
        Status: data.Status ?? 'A',
      },
    });
  }

  async upsertVoucherTDS(VoucherHeaderSid: number, data: CreateVoucherTDSDto, tx: Tx) {
    const existing = await tx.voucherTDS.findFirst({
      where: { VoucherHeaderSid, Status: 'A' },
    });
    if (existing) {
      return tx.voucherTDS.update({
        where: { VoucherTDSSid: existing.VoucherTDSSid },
        data: {
          TDSSetRateSid: data.TDSSetRateSid,
          ITSectionCode: data.ITSectionCode,
          TDSRate: Math.round(Number(data.TDSRate) || 0),
          TaxableAmount: data.TaxableAmount,
          TDSAmount: data.TDSAmount,
          TDSPartyAmount: data.TDSPartyAmount ?? null,
          Reason: data.Reason ?? null,
          UpdatedBy: data.UpdatedBy ?? 'system',
          UpdatedOn: new Date(),
        },
      });
    }
    return this.createVoucherTDS({ ...data, VoucherHeaderSid }, tx);
  }

  async removeVoucherTDS(VoucherHeaderSid: number, tx: Tx): Promise<void> {
    await tx.voucherTDS.updateMany({
      where: { VoucherHeaderSid, Status: 'A' },
      data: { Status: 'D', UpdatedOn: new Date() },
    });
  }
}
